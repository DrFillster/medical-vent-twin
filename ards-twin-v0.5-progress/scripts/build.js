// Dependency-free CommonJS bundler for this project's local, static requires.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const modules = new Map();
function collect(id) {
  if (modules.has(id)) return;
  let source = fs.readFileSync(path.join(root, id), 'utf8');
  modules.set(id, '');
  source = source.replace(/require\(['"]([^'"]+)['"]\)/g, (_, dependency) => {
    if (!dependency.startsWith('.')) throw new Error(`External dependency: ${dependency}`);
    const target = path.posix.normalize(path.posix.join(path.posix.dirname(id), dependency));
    if (!target.startsWith('src/') || !target.endsWith('.js')) throw new Error(`Unexpected module: ${target}`);
    collect(target);
    return `require(${JSON.stringify(target)})`;
  });
  modules.set(id, source);
}
collect('src/browser-entry.js');
const entries = [...modules].map(([id, source]) => `${JSON.stringify(id)}:function(module,exports,require){\n${source}\n}`).join(',\n');
const bundle = `/* Generated by npm run build. Version 0.6.0-preview.1. */\n'use strict';\nvar VENT = (() => {\nconst modules={${entries}};\nconst cache={};\nfunction require(id){if(cache[id])return cache[id].exports;const m=cache[id]={exports:{}};modules[id](m,m.exports,require);return m.exports;}\nreturn require('src/browser-entry.js');\n})();\n`;
fs.writeFileSync(path.join(root, 'web/engine.js'), bundle);
console.log(`Built web/engine.js from ${modules.size} source modules.`);


/* HumMod-Lab gateway bundle: publish all browser code through /app.js and
 * duplicate the v2.0 stylesheet at /style.css because the external gateway
 * only proxies exact paths "/", "/app.js", and "/style.css".
 */
const webDir = path.join(root, 'web');
const appSourcePath = path.join(webDir, 'app-source.js');
if (fs.existsSync(appSourcePath)) {
  let appSource = fs.readFileSync(appSourcePath, 'utf8');
  const clinicalCases = fs.readFileSync(path.join(webDir, 'clinical-cases.json'), 'utf8');
  const clinicalWorker = fs.readFileSync(path.join(webDir, 'clinical-worker.js'), 'utf8')
    .replace(/^['"]use strict['"];?\s*/,'')
    .replace(/importScripts\([^\n]+\);?\s*/,'');
  const legacyWorker = fs.readFileSync(path.join(webDir, 'worker.js'), 'utf8')
    .replace(/^['"]use strict['"];?\s*/,'')
    .replace(/importScripts\([^\n]+\);?\s*/,'');

  const helper =
`\nwindow.__VENT_CLINICAL_CASES__ = ${clinicalCases};\n` +
`const __VENT_CLINICAL_WORKER_SOURCE__ = ${JSON.stringify(bundle + '\n' + clinicalWorker)};\n` +
`const __VENT_LEGACY_WORKER_SOURCE__ = ${JSON.stringify(bundle + '\n' + legacyWorker)};\n` +
`function __ventInlineWorker(source){\n` +
`  const blob = new Blob([source], {type:'text/javascript'});\n` +
`  return new Worker(URL.createObjectURL(blob));\n` +
`}\n`;

  appSource = appSource
    .replace("new Worker('./clinical-worker.js?v=0.6')",
      "__ventInlineWorker(__VENT_CLINICAL_WORKER_SOURCE__)")
    .replace("new Worker('./worker.js?v=0.4.5')",
      "__ventInlineWorker(__VENT_LEGACY_WORKER_SOURCE__)");

  fs.writeFileSync(path.join(webDir, 'app.js'), bundle + helper + appSource);
  fs.copyFileSync(path.join(webDir, 'styles.css'), path.join(webDir, 'style.css'));
  console.log('Built gateway-compatible web/app.js and web/style.css.');
}
